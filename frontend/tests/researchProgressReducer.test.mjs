import test from 'node:test'
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { fileURLToPath } from 'node:url'

const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), configFile: false, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false, watch: null } })
test.after(() => server.close())
const { createProgressSnapshot, reduceResearchProgress: reduce, sanitizeResearchProgress: sanitize, setProgressTransport, PROGRESS_LIMITS } = await server.ssrLoadModule('/src/utils/researchProgress.js')
const start = (runId, timestamp = 10) => ({ runId, workflow: 'RESEARCH_WRITE_REVIEW', topic: 'topic', stage: 'RESEARCHING', operation: 'WORKFLOW', status: 'RUNNING', timestamp })
const active = s => s.runs.find(run => run.runId === s.activeRunId)

test('only WORKFLOW RUNNING starts a run, tools do not regress stage and stale runs are ignored', () => {
  let s = reduce(null, { runId: 'a', operation: 'DOWNLOAD', status: 'RUNNING', paper: 'paper', timestamp: 1 })
  assert.equal(s.runs.length, 0)
  s = reduce(s, start('a'))
  s = reduce(s, { ...start('a', 30), stage: 'REVIEWING', counts: { total: 7, succeeded: 3 } })
  s = reduce(s, { runId: 'a', operation: 'DOWNLOAD', status: 'SUCCEEDED', paper: 'paper', stage: 'RESEARCHING', timestamp: 40 })
  assert.equal(active(s).stage, 'REVIEWING')
  assert.deepEqual(active(s).counts, { total: 7, succeeded: 3 })
  s = reduce(s, { ...start('a', 20), stage: 'WRITING' })
  assert.equal(active(s).stage, 'REVIEWING')
  s = reduce(s, start('b', 50))
  assert.deepEqual(reduce(s, { runId: 'a', operation: 'DOWNLOAD', status: 'SUCCEEDED', paper: 'late', timestamp: 60 }), s)
  assert.deepEqual(reduce(s, start('a', 70)), s)
  assert.deepEqual(reduce(s, start('unknown-old', 40)), s)
})

test('paper operations respect timestamps and terminal state; workflow result is independent of transport', () => {
  let s = reduce(null, start('a'))
  s = reduce(s, { runId: 'a', operation: 'ANALYSIS', status: 'SUCCEEDED', paper: 'p', timestamp: 30 })
  s = reduce(s, { runId: 'a', operation: 'ANALYSIS', status: 'RUNNING', paper: 'p', timestamp: 20 })
  s = reduce(s, { runId: 'a', operation: 'ANALYSIS', status: 'RUNNING', paper: 'p', timestamp: 40 })
  assert.equal(active(s).papers[0].operations.ANALYSIS.status, 'SUCCEEDED')
  s = reduce(s, { runId: 'a', operation: 'STAGE', stage: 'WRITING', status: 'RUNNING', counts: { total: 8 }, timestamp: 42 })
  assert.equal(active(s).stage, 'WRITING')
  s = reduce(s, { runId: 'a', operation: 'STAGE', status: 'SUCCEEDED', stage: 'ANALYZING', timestamp: 43 })
  assert.equal(active(s).status, 'RUNNING')
  assert.equal(active(s).stage, 'ANALYZING')
  s = reduce(s, { runId: 'a', operation: 'ANALYSIS', status: 'RUNNING', counts: { total: 3, completed: 1 }, timestamp: 44 })
  s = reduce(s, { runId: 'a', operation: 'DOWNLOAD', status: 'SUCCEEDED', paper: 'p', counts: { completed: 1 }, timestamp: 45 })
  assert.deepEqual(active(s).counts, { total: 8 })
  assert.deepEqual(active(s).operations.ANALYSIS.counts, { total: 3, completed: 1 })
  assert.deepEqual(active(s).papers[0].operations.DOWNLOAD.counts, { completed: 1 })
  assert.equal(active(s).stage, 'ANALYZING')
  assert.deepEqual(reduce(s, { stage: 'RESEARCHING', timestamp: 46 }), s)
  s = reduce(s, { ...start('a', 50), stage: 'DONE', status: 'LIMIT_REACHED' })
  s = setProgressTransport(s, 'done')
  assert.equal(active(s).status, 'LIMIT_REACHED')
  assert.equal(s.transportStatus, 'done')
  assert.equal(active(sanitize(s, { restored: true })).status, 'LIMIT_REACHED')
})

test('legacy events only describe stage and detail, never parse paper counts from Chinese', () => {
  let s = reduce(null, { stage: 'ANALYZING', label: '正在精读', round: 2, detail: '已精读 5/6 篇 paper.pdf', timestamp: 10 })
  assert.equal(active(s).legacy, true)
  assert.equal(active(s).stage, 'ANALYZING')
  assert.equal(active(s).round, 2)
  assert.deepEqual(active(s).counts, {})
  assert.equal(active(s).papers.length, 0)
  assert.equal(active(s).activity[0].detail, '已精读 5/6 篇 paper.pdf')
  s = reduce(s, { stage: 'FAILED', label: '精读失败', timestamp: 20 })
  assert.equal(active(s).stage, 'FAILED')
  assert.equal(active(s).status, '')
})

test('snapshots are pure, bounded by run/paper/activity/string/UTF8 limits and drop unsafe fields', () => {
  let s = createProgressSnapshot()
  for (let i = 0; i < 5; i++) s = reduce(s, start(`r${i}`, 10 + i))
  assert.equal(s.runs.length, 3)
  const previous = structuredClone(s)
  s = reduce(s, { runId: 'r4', operation: 'DOWNLOAD', status: 'RUNNING', paper: 'p', detail: 'x', timestamp: 100 })
  assert.deepEqual(previous.runs.at(-1).papers, [])
  for (let i = 0; i < 150; i++) s = reduce(s, { runId: 'r4', operation: 'DOWNLOAD', status: 'RUNNING', paper: `p${i}`, detail: 'd', timestamp: 110 + i })
  assert.equal(active(s).papers.length, 100)
  assert.equal(active(s).papersTruncated, true)
  assert.equal(active(s).activity.length, 40)
  for (let i = 0; i < 100; i++) s = reduce(s, { runId: 'r4', operation: `OP${i % 8}`, status: 'RUNNING', paper: `p${i}`, detail: '字'.repeat(10000), timestamp: 300 + i })
  assert.ok(new TextEncoder().encode(JSON.stringify(s)).length <= PROGRESS_LIMITS.bytes)
  assert.ok(active(s).papers.length <= 100)
  assert.ok(active(s).activity.length <= 40)
  assert.ok(active(s).activity.every(item => item.detail.length <= 512))
  assert.equal(sanitize({ ...s, secret: 'bad' }).secret, undefined)
  assert.equal(sanitize(null), null)
  assert.equal(sanitize('bad'), null)
})

test('sanitize validates counts and marks restored running transport unknown without fabricating success', () => {
  const s = reduce(null, { ...start('a'), counts: { total: 8, completed: NaN, succeeded: -1, failed: 2, skipped: 0, active: 1, guessed: 4 } })
  assert.deepEqual(active(s).counts, { total: 8, failed: 2, skipped: 0, active: 1 })
  const clean = sanitize(s, { restored: true })
  assert.equal(clean.transportStatus, 'unknown')
  assert.equal(active(clean).status, 'RUNNING')
})
